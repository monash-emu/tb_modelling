"""SLURM job generation for the MASSIVE cluster.

The published setup kept ``#SBATCH --array=1-16`` in a hand-edited shell script while the
parameter grid was defined separately in Python. Those two numbers had to be kept in step by
hand, and a mismatch either silently drops tasks or submits tasks that fail on an index
error. Here the array range is derived from the grid, so they cannot diverge.

Paths are supplied rather than hard-coded: the published script embedded an absolute path to
a repository under its former name.
"""

from dataclasses import dataclass, field
from pathlib import Path

import yaml

SBATCH_TEMPLATE = """#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --account={account}
#SBATCH --time={walltime}
#SBATCH --ntasks=1
#SBATCH --mem-per-cpu={mem_per_cpu}
#SBATCH --cpus-per-task={cpus}
#SBATCH --output={log_dir}/%A_%a.out
#SBATCH --mail-user={email}
#SBATCH --mail-type=BEGIN,END,FAIL
#SBATCH --array=1-{n_tasks}

# Generated by tbcore.hpc — do not edit by hand; the array range is derived from the
# parameter grid and will be overwritten.

set -euo pipefail

log() {{ echo "[$(date '+%Y-%m-%d %H:%M:%S')] $@"; }}
log "Starting task ${{SLURM_ARRAY_TASK_ID}} of {n_tasks}"

mkdir -p {log_dir}

# Each task needs its own pytensor compile directory, or concurrent tasks corrupt one
# another's compiled cache.
export PYTENSOR_FLAGS="compiledir=$HOME/.pytensor/${{SLURM_ARRAY_JOB_ID}}_${{SLURM_ARRAY_TASK_ID}}"
export TB_OUTPUT_ROOT="{output_root}"

cd {repo_dir}

# Stagger starts so that tasks do not contend while building the environment.
sleep $((SLURM_ARRAY_TASK_ID * {stagger_seconds}))

pixi run python {entry_point} $SLURM_ARRAY_JOB_ID $SLURM_ARRAY_TASK_ID

log "Task completed"
"""


@dataclass
class JobSpec:
    """Everything needed to generate a SLURM array job."""

    job_name: str
    entry_point: str
    repo_dir: str
    output_root: str
    log_dir: str
    account: str = "sh30"
    email: str = "romain.ragonnet@monash.edu"
    walltime: str = "48:00:00"
    cpus: int = 8
    mem_per_cpu: str = "8G"
    stagger_seconds: int = 30
    grid: list = field(default_factory=list)

    def n_tasks(self) -> int:
        # A grid of zero length would produce `--array=1-0`, which SLURM rejects with an
        # unhelpful message; catch it here instead.
        if not self.grid:
            raise ValueError(
                f"Job '{self.job_name}' has an empty parameter grid, so there is nothing "
                "to submit."
            )
        return len(self.grid)


def write_sbatch(spec: JobSpec, path: Path) -> Path:
    """Write the submission script, with the array range derived from the grid."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        SBATCH_TEMPLATE.format(
            job_name=spec.job_name,
            account=spec.account,
            walltime=spec.walltime,
            mem_per_cpu=spec.mem_per_cpu,
            cpus=spec.cpus,
            log_dir=spec.log_dir,
            email=spec.email,
            n_tasks=spec.n_tasks(),
            output_root=spec.output_root,
            repo_dir=spec.repo_dir,
            entry_point=spec.entry_point,
            stagger_seconds=spec.stagger_seconds,
        )
    )
    path.chmod(0o755)
    return path


def write_task_map(spec: JobSpec, path: Path) -> Path:
    """Record which task index corresponds to which grid entry.

    Without this, interpreting an array job's outputs months later means re-deriving the
    grid from whatever the code looked like at the time.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as handle:
        yaml.safe_dump(
            {
                "job_name": spec.job_name,
                "n_tasks": spec.n_tasks(),
                "task_to_config": dict(enumerate(spec.grid, start=1)),
            },
            handle,
            sort_keys=False,
        )
    return path


def task_config(spec: JobSpec, task_id: int) -> dict:
    """Grid entry for a SLURM array task index, which is one-based."""
    if not 1 <= task_id <= spec.n_tasks():
        raise ValueError(
            f"Task id {task_id} is outside the array range 1-{spec.n_tasks()} for job "
            f"'{spec.job_name}'."
        )
    return spec.grid[task_id - 1]
